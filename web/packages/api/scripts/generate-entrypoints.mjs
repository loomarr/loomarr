import { readdir, rm, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = fileURLToPath(new URL("../", import.meta.url));
const generatedRoot = join(packageRoot, "generated");
const generatedPrefixes = ["endpoint-", "model-", "zod-"];

const rootEntries = await readdir(packageRoot, { withFileTypes: true });
await Promise.all(
  rootEntries
    .filter(
      (entry) =>
        entry.isFile() &&
        entry.name.endsWith(".ts") &&
        generatedPrefixes.some((prefix) => entry.name.startsWith(prefix)),
    )
    .map((entry) => rm(join(packageRoot, entry.name))),
);

const writeEntrypoint = async (name, target) => {
  const source = `// Generated by scripts/generate-entrypoints.mjs. Do not edit.\nexport * from "${target}";\n`;
  await writeFile(join(packageRoot, name), source);
};

const models = (await readdir(join(generatedRoot, "model"), { withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name.endsWith(".ts"))
  .map((entry) => basename(entry.name, ".ts"))
  .sort();

const endpointTags = (await readdir(join(generatedRoot, "endpoints"), { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const zodTags = (await readdir(join(generatedRoot, "zod"), { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

await Promise.all([
  ...models.map((model) => writeEntrypoint(`model-${model}.ts`, `./generated/model/${model}`)),
  ...endpointTags.map((tag) => writeEntrypoint(`endpoint-${tag}.ts`, `./generated/endpoints/${tag}/${tag}`)),
  ...zodTags.map((tag) => writeEntrypoint(`zod-${tag}.ts`, `./generated/zod/${tag}/${tag}.zod`)),
]);
