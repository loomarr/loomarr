const fs = require("node:fs");
const path = require("node:path");
const {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
  withSettingsGradle,
} = require("@expo/config-plugins");

const settingsMarker = "// @generated by with-tv-macrobenchmark";

const macrobenchmarkBuildGradle = `plugins {
    id 'com.android.test'
    id 'org.jetbrains.kotlin.android'
}

android {
    namespace 'media.loomarr.tv.macrobenchmark'
    compileSdk rootProject.ext.compileSdkVersion

    defaultConfig {
        minSdkVersion 23
        targetSdkVersion rootProject.ext.targetSdkVersion
        testInstrumentationRunner 'androidx.test.runner.AndroidJUnitRunner'
    }

    targetProjectPath = ':app'

    buildTypes {
        benchmark {
            debuggable = true
            matchingFallbacks = ['release']
        }
    }
}

dependencies {
    implementation 'androidx.test.ext:junit:1.3.0'
    implementation 'androidx.test.uiautomator:uiautomator:2.4.0'
    implementation 'androidx.benchmark:benchmark-macro-junit4:1.4.1'
}
`;

const macrobenchmarkManifest = `<manifest />
`;

const guideNavigationBenchmark = `package media.loomarr.tv.macrobenchmark

import android.os.SystemClock
import androidx.benchmark.macro.CompilationMode
import androidx.benchmark.macro.FrameTimingMetric
import androidx.benchmark.macro.junit4.MacrobenchmarkRule
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.filters.LargeTest
import androidx.test.uiautomator.By
import androidx.test.uiautomator.Until
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

private const val TARGET_PACKAGE = "media.loomarr.tv.prototype"
private const val WAIT_MS = 20_000L

@LargeTest
@RunWith(AndroidJUnit4::class)
class GuideNavigationBenchmark {
    @get:Rule
    val benchmarkRule = MacrobenchmarkRule()

    @Test
    fun guideNavigation() = benchmarkRule.measureRepeated(
        packageName = TARGET_PACKAGE,
        metrics = listOf(FrameTimingMetric()),
        compilationMode = CompilationMode.Ignore(),
        iterations = 8,
        setupBlock = {
            pressHome()
            startActivityAndWait()
            assertTrue(
                "The TV client must already be paired and showing Watching before the Shield benchmark",
                device.wait(Until.hasObject(By.desc("Show playback controls")), WAIT_MS),
            )
            device.pressDPadCenter()
            assertTrue(
                "The paired server must expose a populated Guide before the Shield benchmark",
                device.wait(Until.hasObject(By.desc("Programme guide")), WAIT_MS),
            )
        },
    ) {
        repeat(12) {
            device.pressDPadRight()
            SystemClock.sleep(40)
            device.pressDPadDown()
            SystemClock.sleep(40)
            device.pressDPadLeft()
            SystemClock.sleep(40)
            device.pressDPadUp()
            SystemClock.sleep(40)
        }
        device.waitForIdle()
    }
}
`;

const addMacrobenchmarkSettings = (contents) => {
  if (contents.includes(settingsMarker)) return contents;
  return `${contents.trimEnd()}\n\n${settingsMarker}\ninclude ':macrobenchmark'\n`;
};

const addProfileableApplication = (manifest) => {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
  const existing = application.profileable ?? [];
  if (!existing.some((entry) => entry.$?.["android:shell"] === "true")) {
    application.profileable = [...existing, { $: { "android:shell": "true" } }];
  }
  return manifest;
};

const writeMacrobenchmarkModule = (projectRoot) => {
  const moduleRoot = path.join(projectRoot, "android", "macrobenchmark");
  const sourceRoot = path.join(
    moduleRoot,
    "src",
    "main",
    "java",
    "media",
    "loomarr",
    "tv",
    "macrobenchmark",
  );
  fs.mkdirSync(sourceRoot, { recursive: true });
  fs.writeFileSync(path.join(moduleRoot, "build.gradle"), macrobenchmarkBuildGradle);
  fs.writeFileSync(path.join(moduleRoot, "src", "main", "AndroidManifest.xml"), macrobenchmarkManifest);
  fs.writeFileSync(path.join(sourceRoot, "GuideNavigationBenchmark.kt"), guideNavigationBenchmark);
};

const withTvMacrobenchmark = (config) => {
  config = withSettingsGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== "groovy") {
      throw new Error("Loomarr's TV Macrobenchmark expects Groovy Android settings");
    }
    gradleConfig.modResults.contents = addMacrobenchmarkSettings(gradleConfig.modResults.contents);
    return gradleConfig;
  });
  config = withAndroidManifest(config, (manifestConfig) => {
    manifestConfig.modResults = addProfileableApplication(manifestConfig.modResults);
    return manifestConfig;
  });
  return withDangerousMod(config, ["android", async (modConfig) => {
    writeMacrobenchmarkModule(modConfig.modRequest.projectRoot);
    return modConfig;
  }]);
};

module.exports = withTvMacrobenchmark;
module.exports.addMacrobenchmarkSettings = addMacrobenchmarkSettings;
module.exports.addProfileableApplication = addProfileableApplication;
module.exports.guideNavigationBenchmark = guideNavigationBenchmark;
module.exports.macrobenchmarkBuildGradle = macrobenchmarkBuildGradle;
module.exports.writeMacrobenchmarkModule = writeMacrobenchmarkModule;
