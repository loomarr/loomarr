const { withAppBuildGradle } = require("@expo/config-plugins");

const startMarker = "// @generated by with-memory-safe-android-build";

/**
 * Keep React Native's CMake/Ninja compilation bounded on developer machines.
 * Gradle's worker limit does not constrain native compiler processes, so the
 * generated Android project also needs explicit CMake compile and link pools.
 */
function addMemorySafeAndroidBuild(contents) {
  if (contents.includes(startMarker)) {
    return contents;
  }

  const defaultConfig = "    defaultConfig {\n";
  if (!contents.includes(defaultConfig)) {
    throw new Error("Could not find Android defaultConfig while applying Loomarr's build limiter");
  }

  const nativePools = `        ${startMarker}
        externalNativeBuild {
            cmake {
                arguments "-DCMAKE_JOB_POOLS=loomarr_compile=1;loomarr_link=1",
                    "-DCMAKE_JOB_POOL_COMPILE=loomarr_compile",
                    "-DCMAKE_JOB_POOL_LINK=loomarr_link"
            }
        }
`;

  return contents.replace(defaultConfig, `${defaultConfig}${nativePools}`);
}

function withMemorySafeAndroidBuild(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== "groovy") {
      throw new Error("Loomarr's Android build limiter expects a Groovy app build file");
    }

    gradleConfig.modResults.contents = addMemorySafeAndroidBuild(
      gradleConfig.modResults.contents,
    );
    return gradleConfig;
  });
}

module.exports = withMemorySafeAndroidBuild;
module.exports.addMemorySafeAndroidBuild = addMemorySafeAndroidBuild;
