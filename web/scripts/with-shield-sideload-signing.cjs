const { withAppBuildGradle } = require("@expo/config-plugins");

const marker = "// @generated by with-shield-sideload-signing";

function addShieldSideloadSigning(contents) {
  if (contents.includes(marker)) return contents;

  const signingClose = "    }\n    buildTypes {\n";
  const releaseSigning = /(buildTypes\s*\{[\s\S]*?release\s*\{[\s\S]*?)signingConfig signingConfigs\.debug/;
  if (!contents.includes("android {\n") || !contents.includes(signingClose) || !releaseSigning.test(contents)) {
    throw new Error("Could not find Expo's generated Android signing configuration");
  }

  const releaseInputs = `${marker}
def loomarrShieldSideload = System.getenv("LOOMARR_SHIELD_SIDELOAD") == "1"
def loomarrReleaseStoreFile = System.getenv("LOOMARR_ANDROID_KEYSTORE_PATH")
def loomarrReleaseStorePassword = System.getenv("LOOMARR_ANDROID_KEYSTORE_PASSWORD")
def loomarrReleaseKeyAlias = System.getenv("LOOMARR_ANDROID_KEY_ALIAS")
def loomarrReleaseKeyPassword = System.getenv("LOOMARR_ANDROID_KEY_PASSWORD")
if (loomarrShieldSideload && [loomarrReleaseStoreFile, loomarrReleaseStorePassword, loomarrReleaseKeyAlias, loomarrReleaseKeyPassword].any { !it }) {
    throw new GradleException("Shield sideload requires every Loomarr signing input")
}

android {
`;
  const productionSigning = `        if (loomarrShieldSideload) {
            release {
                storeFile file(loomarrReleaseStoreFile)
                storePassword loomarrReleaseStorePassword
                keyAlias loomarrReleaseKeyAlias
                keyPassword loomarrReleaseKeyPassword
            }
        }
    }
    buildTypes {
`;

  return contents
    .replace("android {\n", releaseInputs)
    .replace(signingClose, productionSigning)
    .replace(
      releaseSigning,
      "$1signingConfig loomarrShieldSideload ? signingConfigs.release : signingConfigs.debug",
    );
}

function withShieldSideloadSigning(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== "groovy") {
      throw new Error("Loomarr's Shield signing expects a Groovy app build file");
    }
    gradleConfig.modResults.contents = addShieldSideloadSigning(gradleConfig.modResults.contents);
    return gradleConfig;
  });
}

module.exports = withShieldSideloadSigning;
module.exports.addShieldSideloadSigning = addShieldSideloadSigning;
