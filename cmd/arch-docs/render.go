package main

import (
	"fmt"
	"sort"
	"strings"
)

// beginMarker/endMarker delimit the generated block inside docs/design/package-map.md.
//
// A marker pair rather than whole-file generation (which is how docs/reference/settings.md
// works): the page's heading and introduction are hand-written, so this tool owns one
// block inside it and must not be able to touch a word outside that block.
const (
	beginMarker = "<!-- BEGIN GENERATED: package-map — `make arch-docs`. DO NOT EDIT BY HAND. -->"
	endMarker   = "<!-- END GENERATED: package-map -->"
)

// areaPagesDir holds one generated page per area, beside the package map. The generator
// owns the whole directory: a file there that is not an area page is removed.
const areaPagesDir = "areas"

// spineFanIn is the importer count at which a package is part of the load-bearing spine.
//
// The spine is a short table, not the whole graph: 100 packages and their edges read as a
// hairball nobody follows. The full edge set is on the area pages, which are greppable.
const spineFanIn = 5

// render produces the generated block for the package-map page: the area index, the two
// traced flows and the dependency spine.
//
// It carries no per-package rows or counts. Those change on most PRs, and in one shared
// block every such PR edited the same lines, so the merge queue dropped whichever landed
// second. They live on the area pages, where an import change touches only the areas whose
// packages it names. Deterministic by construction — every list is sorted.
func render(table []area, pkgs []Package) string {
	var b strings.Builder

	b.WriteString(beginMarker + "\n\n")
	b.WriteString("## Start here\n\n")
	b.WriteString("The packages under `internal/` group into the areas below. Each area has its own " +
		"generated page listing its packages, what each one imports, how many packages import it, " +
		"and which other areas it reaches into (counted as package-to-package imports), each with " +
		"the reason. The area table lives in `cmd/arch-docs/areas.go`; a new package must be added " +
		"to one area before it merges, and a new import into another area must be declared there " +
		"with its reason. A reason ending \"until …\" is an import that should go.\n\n")
	for _, a := range table {
		fmt.Fprintf(&b, "### [%s](%s/%s.md)\n\n%s\n\n", a.Title, areaPagesDir, a.Name, a.Description)
	}

	b.WriteString("## Two flows, end to end\n\n")
	for _, f := range flows {
		fmt.Fprintf(&b, "### %s\n\n%s\n\n", f.Title, f.Text)
	}

	b.WriteString(renderSpine(pkgs, fanInCounts(pkgs)))

	b.WriteString("## How the area pages are made\n\n")
	b.WriteString("Generated recursively from each package's own doc comment and exact internal imports, ")
	b.WriteString("using full paths below `internal/`, so they cannot drift from the code the way a ")
	b.WriteString("hand-maintained list does. Sizes are deliberately absent — they change on nearly every ")
	b.WriteString("commit, which would make the drift check red by default and train everyone to ")
	b.WriteString("regenerate without reading.\n\n")

	b.WriteString(endMarker)
	return b.String()
}

// renderAreaPages produces one whole page per area, keyed by area name: its description,
// the other areas it imports from, and each of its production packages with its importer
// count, imports and synopsis. Packages the scan does not see (directories of tests alone)
// are named on one line, so they never read as production rows.
func renderAreaPages(table []area, pkgs []Package) map[string]string {
	areaOf := map[string]string{}
	for _, a := range table {
		for _, p := range a.Packages {
			areaOf[p] = a.Name
		}
	}
	byName := make(map[string]Package, len(pkgs))
	for _, p := range pkgs {
		byName[p.Name] = p
	}
	fanIn := fanInCounts(pkgs)

	pages := make(map[string]string, len(table))
	for _, a := range table {
		var b strings.Builder
		fmt.Fprintf(&b, "# %s\n\n", a.Title)
		b.WriteString("<!-- GENERATED by `make arch-docs` from cmd/arch-docs/areas.go and the code. " +
			"DO NOT EDIT BY HAND. -->\n\n")
		fmt.Fprintf(&b, "%s\n\n", a.Description)
		b.WriteString("One area of the [package map](../package-map.md#start-here).\n\n")
		renderAreaImports(&b, a, crossAreaImports(a, byName, areaOf, table))
		b.WriteString("## Packages\n\n")

		names := append([]string(nil), a.Packages...)
		sort.Strings(names)
		var testsOnly []string
		for _, n := range names {
			p, ok := byName[n]
			if !ok {
				testsOnly = append(testsOnly, n)
				continue
			}
			fmt.Fprintf(&b, "- **`%s`**", n)
			if count := fanIn[n]; count > 0 {
				fmt.Fprintf(&b, " · %d %s", count, plural(count, "importer"))
			}
			if len(p.Imports) > 0 {
				fmt.Fprintf(&b, " · → %s", codeList(p.Imports))
			}
			b.WriteString("\n")
			if p.Synopsis != "" {
				fmt.Fprintf(&b, "  %s\n", p.Synopsis)
			}
		}
		if len(testsOnly) > 0 {
			fmt.Fprintf(&b, "\n**Tests only:** %s\n", codeList(testsOnly))
		}
		pages[a.Name] = b.String()
	}
	return pages
}

// renderAreaImports writes the other areas a imports from, busiest first, each with the reason
// its MayImport declares. An area that may import any area gets the counts on one line.
func renderAreaImports(b *strings.Builder, a area, counts []areaCount) {
	if len(counts) == 0 {
		b.WriteString("**Imports from other areas:** none\n\n")
		return
	}
	if a.ImportsAnyArea {
		parts := make([]string, len(counts))
		for i, c := range counts {
			parts[i] = fmt.Sprintf("%s (%d)", c.Area, c.Count)
		}
		fmt.Fprintf(b, "**Imports from other areas:** any, by design — %s\n\n", strings.Join(parts, ", "))
		return
	}
	b.WriteString("## Imports from other areas\n\n")
	for _, c := range counts {
		fmt.Fprintf(b, "- **%s** · %d %s — %s\n", c.Area, c.Count, plural(c.Count, "import"), a.MayImport[c.Area])
	}
	b.WriteString("\n")
}

// renderSpine lists the packages that most of the tree depends on, without their importer
// counts: the counts move on most PRs, membership of the spine rarely does.
func renderSpine(pkgs []Package, fanIn map[string]int) string {
	spine := map[string]bool{}
	for _, p := range pkgs {
		if fanIn[p.Name] >= spineFanIn {
			spine[p.Name] = true
		}
	}
	if len(spine) == 0 {
		return ""
	}

	var b strings.Builder
	b.WriteString("## Dependency spine\n\n")
	fmt.Fprintf(&b, "Packages imported by %d or more others, and their dependencies within the spine. ",
		spineFanIn)
	b.WriteString("Everything else in the tree sits on top of these packages.\n\n")
	b.WriteString("| Package | Depends on |\n")
	b.WriteString("| --- | --- |\n")

	byName := make(map[string]Package, len(pkgs))
	for _, p := range pkgs {
		byName[p.Name] = p
	}
	for _, n := range sortedKeys(spine) {
		var deps []string
		for _, dep := range byName[n].Imports {
			if spine[dep] {
				deps = append(deps, dep)
			}
		}
		dependencyList := "—"
		if len(deps) > 0 {
			dependencyList = codeList(deps)
		}
		fmt.Fprintf(&b, "| `%s` | %s |\n", n, dependencyList)
	}
	b.WriteString("\n")
	return b.String()
}

// fanInCounts counts, for each package, how many others import it directly.
func fanInCounts(pkgs []Package) map[string]int {
	counts := map[string]int{}
	for _, p := range pkgs {
		for _, dep := range p.Imports {
			counts[dep]++
		}
	}
	return counts
}

// splice replaces the generated block in doc, or appends it to the named section
// when no block exists yet. Returns an error rather than guessing if the markers are
// malformed — a half-matched marker pair would silently eat hand-written prose.
func splice(doc, block, anchor string) (string, error) {
	start := strings.Index(doc, beginMarker)
	end := strings.Index(doc, endMarker)

	switch {
	case start >= 0 && end > start:
		return doc[:start] + block + doc[end+len(endMarker):], nil
	case start >= 0 || end >= 0:
		return "", fmt.Errorf("the package-map page has one half of the generated-block marker pair but not the other; " +
			"repair it by hand — regenerating over a malformed pair would delete prose")
	}

	// First run: insert after the anchor heading's section.
	idx := strings.Index(doc, anchor)
	if idx < 0 {
		return "", fmt.Errorf("anchor %q not found in the package-map page", anchor)
	}
	// Insert immediately before the next top-level heading after the anchor, so the
	// block lands at the end of §2 rather than in the middle of its prose.
	rest := doc[idx+len(anchor):]
	next := strings.Index(rest, "\n## ")
	if next < 0 {
		return strings.TrimRight(doc, "\n") + "\n\n" + block + "\n", nil
	}
	at := idx + len(anchor) + next
	// Trim the section's trailing blank lines before splicing, so the block lands with
	// exactly one blank line on each side however the hand-written prose above it ends.
	// doc[at:] already begins with the newline that starts the next heading.
	return strings.TrimRight(doc[:at], "\n") + "\n\n" + block + "\n" + doc[at:], nil
}

// plural is the tiny grammar helper the map needs so "1 importers" never ships in a
// document whose whole job is to be read.
func plural(n int, word string) string {
	if n == 1 {
		return word
	}
	return word + "s"
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func codeList(names []string) string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = "`" + n + "`"
	}
	return strings.Join(out, ", ")
}
