#!/usr/bin/env bash
# Bring web/ in line with this checkout before a frontend dev server starts. A pull, rebase or branch
# switch can change the lockfile, the OpenAPI spec or the design tokens without touching
# node_modules or the generated sources, and Vite then fails on imports that no longer resolve.
#
# Usage: scripts/dev/fe-sync.sh          install and regenerate only when the inputs changed
#        FE_SYNC_FORCE=1 scripts/dev/fe-sync.sh   always (make bootstrap)
#
# The inputs' checksum is kept in web/node_modules, so a fresh or deleted install syncs again. The
# design system is read from git's index (committed and staged state); an unstaged edit to its
# sources is regenerated by `make fe-codegen`, as before.

set -euo pipefail

ROOT="$(CDPATH='' cd -- "$(dirname -- "$0")/../.." && pwd -P)"
cd "$ROOT"
stamp=web/node_modules/.loomarr-fe-sync

inputs() {
	{
		cat web/pnpm-lock.yaml api/openapi.yaml
		git ls-files -s web/packages/design-system
	} | cksum | cut -d' ' -f1
}

want="$(inputs)"
if [ "${FE_SYNC_FORCE:-0}" != 1 ] && [ -f "$stamp" ] && [ "$(cat "$stamp")" = "$want" ]; then
	exit 0
fi
[ "${FE_SYNC_FORCE:-0}" = 1 ] || echo 'fe-sync: the lockfile, API spec or design tokens changed; installing and regenerating.' >&2
(cd web && pnpm install --frozen-lockfile && pnpm codegen)
printf '%s\n' "$want" >"$stamp"
