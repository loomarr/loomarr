//go:build ignore

// Command timezones_generate writes timezones_gen.go: every zone name in the Go toolchain's own tz
// data ($GOROOT/lib/time/zoneinfo.zip), sorted. `go generate ./internal/platform/settings` runs it;
// TestTimezonesGenIsCurrent fails when a toolchain bump brings new zones the file lacks.
package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"go/format"
	"log/slog"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

func main() {
	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		slog.Error("go env GOROOT", "err", err)
		os.Exit(1)
	}
	r, err := zip.OpenReader(filepath.Join(strings.TrimSpace(string(goroot)), "lib", "time", "zoneinfo.zip"))
	if err != nil {
		slog.Error("open Go tz data", "err", err)
		os.Exit(1)
	}
	defer r.Close()
	var names []string
	for _, f := range r.File {
		if !f.FileInfo().IsDir() {
			names = append(names, f.Name)
		}
	}
	slices.Sort(names)

	var b bytes.Buffer
	b.WriteString("// Code generated by timezones_generate.go from the Go toolchain's tz data. DO NOT EDIT.\n\n")
	b.WriteString("package settings\n\n")
	b.WriteString("// goZoneNames is every zone name in $GOROOT/lib/time/zoneinfo.zip, sorted.\n")
	b.WriteString("var goZoneNames = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		slog.Error("format", "err", err)
		os.Exit(1)
	}
	if err := os.WriteFile("timezones_gen.go", src, 0o644); err != nil {
		slog.Error("write timezones_gen.go", "err", err)
		os.Exit(1)
	}
}
