package settings

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
	"unicode"
)

// KeysSource renders keys_gen.go: one typed handle per readable setting, in registry order.
// Migration-only settings get none — nothing reads them but their own import.
func (r *Registry) KeysSource() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/settings-keys from the settings registry. DO NOT EDIT.\n\n")
	b.WriteString("package settings\n\n")
	b.WriteString("var (\n")
	seen := map[string]string{}
	for _, s := range r.All() {
		if s.MigrationOnly {
			continue
		}
		name := HandleName(s.Key)
		if other, dup := seen[name]; dup {
			return nil, fmt.Errorf("settings %q and %q both name the handle %s", other, s.Key, name)
		}
		seen[name] = s.Key
		typ, err := handleType(s.Kind)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", s.Key, err)
		}
		fmt.Fprintf(&b, "\t%s = %s{%q}\n", name, typ, s.Key)
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

// HandleName is the exported Go name of a setting key: "filler.vision.provider" is
// FillerVisionProvider, "llm.api_key" is LLMAPIKey.
func HandleName(key string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(key, func(r rune) bool { return r == '.' || r == '_' || r == '-' }) {
		if initialism, ok := initialisms[part]; ok {
			b.WriteString(initialism)
			continue
		}
		runes := []rune(part)
		runes[0] = unicode.ToUpper(runes[0])
		b.WriteString(string(runes))
	}
	return b.String()
}

// initialisms keep Go's spelling for the abbreviations that appear in setting keys.
var initialisms = map[string]string{
	"api": "API", "id": "ID", "url": "URL", "urls": "URLs", "ip": "IP", "tls": "TLS",
	"smtp": "SMTP", "http": "HTTP", "https": "HTTPS", "tz": "TZ", "asr": "ASR",
	"tmdb": "TMDB", "hls": "HLS", "gpu": "GPU", "mqtt": "MQTT", "json": "JSON", "llm": "LLM",
	"ffmpeg": "FFmpeg", "cpu": "CPU", "ttl": "TTL", "sso": "SSO",
}

func handleType(k Kind) (string, error) {
	switch k {
	case KindString, KindEnum, KindURL, KindSecret, KindCron:
		return "StringKey", nil
	case KindInt:
		return "IntKey", nil
	case KindBool:
		return "BoolKey", nil
	case KindDuration:
		return "DurationKey", nil
	case KindStringList:
		return "StringListKey", nil
	}
	return "", fmt.Errorf("no handle type for kind %q", k)
}
